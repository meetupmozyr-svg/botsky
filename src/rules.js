// 3. Определение целевого сценария и точных правил
export function getScopedScenarioRules(query) {
  const q = query.toLowerCase();

  // Сценарий: Неявка / опоздание ученика
  if (/не\s+пришел|не\s+подключ|нет\s+на\s+урок|опазд.*ученик|ученик.*опазд|пропустил.*урок|сколько\s+ждать/i.test(q)) {
    return `
ЦЕЛЕВОЙ СЦЕНАРИЙ: НЕЯВКА ИЛИ ОПОЗДАНИЕ УЧЕНИКА
- Точный статус: Во время ожидания статус не ставится. После 50 минут ожидания выставляется строго «Пропущен учеником».
- Время ожидания: Ровно 50 минут в открытой комнате (обязательное условие для 100% оплаты).
- Если ученик зашел с опозданием: проводите урок ровно до конца запланированного слота по расписанию без продления времени. После окончания выставляется «Урок состоялся».
- Звонок в поддержку: при обычной неявке ученика писать в Teachers Care НЕ требуется.
`;
  }

  // Сценарий: Форс-мажор / отмена преподавателем
  if (/форс-мажор|заболел|нет\s+свет|отключил|срочн.*отмен|я\s+отменяю|не\s+могу\s+провести/i.test(q)) {
    return `
ЦЕЛЕВОЙ СЦЕНАРИЙ: ЭКСТРЕННАЯ ОТМЕНА / ФОРС-МАЖОР ПРЕПОДАВАТЕЛЯ
- Точный статус: «Урок перенесен» (выставляется операторами поддержки).
- Главное правило: Не отменяйте урок самостоятельно в личном кабинете, если до начала осталось менее 24 часов.
- Порядок действий: Срочно напишите дежурным в чат Teachers Care / Mattermost с пометкой «Форс-мажор / Срыв урока» и номерами уроков для снятия расписания без влияния на двухнедельный KPI (ID 310).
- Предупредите ученика в чате платформы вежливым сообщением о переносе по непредвиденным обстоятельствам.
`;
  }

  // Сценарий: Отпуск / перерыв
  if (/отпуск|перерыв|хочу\s+отдохнуть|график\s+перерыв/i.test(q)) {
    return `
ЦЕЛЕВОЙ СЦЕНАРИЙ: ПЕРЕРЫВ И ОТПУСК ПРЕПОДАВАТЕЛЯ
- Точный статус: «Перерыв» оформляется через личный кабинет.
- Срок подачи: Минимум за 14 дней (336 часов). Подача менее чем за 14 дней считается нарушением регламента.
- Ограничение: Новым преподавателям в первые 2 месяца перерыв более 3 дней недоступен.
`;
  }

  // Сценарий: Нулевой баланс
  if (/0\s+на\s+балансе|нулев.*баланс|баланс\s+0/i.test(q)) {
    return `
ЦЕЛЕВОЙ СЦЕНАРИЙ: НУЛЕВОЙ БАЛАНС УЧЕНИКА
- Точный статус: Урок удаляется системой автоматически за 5–10 минут до начала (статус вручную не ставится).
- Правило: Проводить уроки при нулевом балансе запрещено. Если за 8 часов до урока на балансе 0, преподаватель имеет право не выходить на занятие.
`;
  }

  // Сценарий: Отказ от ученика / Смена учителя
  if (/отказ.*ученик|смен.*преподават|ученик.*хочет.*сменить|ушли.*ученик/i.test(q)) {
    return `
ЦЕЛЕВОЙ СЦЕНАРИЙ: ОТКАЗ ОТ УЧЕНИКА И СМЕНА ПРЕПОДАВАТЕЛЯ
- Лимиты по KPI (ID 310): Не более 2 уходов за 2 недели (не более 1 ухода на этапе первых 4 уроков).
- Порядок отказа: Оформляется в разделе «Мои ученики» строго в диапазоне от 72 до 24 часов до урока с указанием обоснованной причины.
`;
  }

  // Сценарий: One Page родителям
  if (/one[\s-]page|обратн.*связ.*родител|отчет.*родител/i.test(q)) {
    return `
ЦЕЛЕВОЙ СЦЕНАРИЙ: ОБРАТНАЯ СВЯЗЬ РОДИТЕЛЯМ (ONE PAGE)
- Регламент: 5-минутный устный диалог в конце урока каждые 20 дней (после от 4 уроков).
- 5 блоков: Прогресс → Зона роста → План → Совет родителю → Личное слово. Формат 9 слайдов отменен.
`;
  }

  // Сценарий: Вводный урок Aloha 3.0
  if (/aloha|алоха|первый\s+урок/i.test(q)) {
    return `
ЦЕЛЕВОЙ СЦЕНАРИЙ: ПЕРВЫЙ УРОК ALOHA 3.0
- Взрослые: 7 этапов Aloha 3.0 (цели, стиль обучения, калибровка уровня, выбор курса, Results Page).
- Пакетные курсы («Английский для жизни», Level Up): уроки Aloha проводить СТРОГО ЗАПРЕЩЕНО (старт сразу с Unit 1).
`;
  }

  return "";
}
